import json
from datetime import datetime
from typing import Optional, Dict, Any
from sqlalchemy import String, DateTime, Text, Float, Boolean, ForeignKey
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    pass


class UserProfileModel(Base):
    """Stores structured user profile data."""
    __tablename__ = "user_profiles"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    user_id: Mapped[str] = mapped_column(String(64), index=True)
    profile_data_json: Mapped[str] = mapped_column(Text, default="{}")
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    def get_profile_dict(self) -> Dict[str, Any]:
        return json.loads(self.profile_data_json) if self.profile_data_json else {}

    def set_profile_dict(self, data: Dict[str, Any]):
        self.profile_data_json = json.dumps(data)


class ApplicationSessionModel(Base):
    """Tracks individual job application automation sessions."""
    __tablename__ = "application_sessions"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    user_id: Mapped[str] = mapped_column(String(64), index=True)
    target_url: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String(32), default="CREATED")
    current_page_title: Mapped[Optional[str]] = mapped_column(String(256), nullable=True)
    current_url: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    submission_approved: Mapped[bool] = mapped_column(Boolean, default=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    updated_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    events: Mapped[list["AgentEventModel"]] = relationship(
        "AgentEventModel", back_populates="session", cascade="all, delete-orphan"
    )


class AgentEventModel(Base):
    """Structured activity log events generated by JobPilot agents."""
    __tablename__ = "agent_events"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    session_id: Mapped[str] = mapped_column(String(36), ForeignKey("application_sessions.id"), index=True)
    event_type: Mapped[str] = mapped_column(String(64))
    message: Mapped[str] = mapped_column(Text)
    details_json: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)

    session: Mapped["ApplicationSessionModel"] = relationship(
        "ApplicationSessionModel", back_populates="events"
    )
